import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const get=name=>readFileSync(new URL(
 '../src/features/portfolio/templates/'+name,import.meta.url),'utf8')

test('Editor preview detects its own scroll rather than waiting for intersection callbacks',()=>{
  const motion=get('ScrollTextAtmosphere.jsx')
  assert.match(motion,/scrollingHost\?\.addEventListener\('scroll',onScroll/)
  assert.match(motion,/document\.addEventListener\('scroll',onScroll/)
  assert.match(motion,/if\(!fallbackFrame\)fallbackFrame=requestAnimationFrame\(scan\)/)
  assert.match(motion,/for\(const part of revealParts\)/)
  assert.match(motion,/classifyPortfolioPart\(part\.getBoundingClientRect\(\),/)
  assert.match(motion,/revealParts\.forEach\(part=>observer\.observe\(part\)\)/)
  assert.match(motion,/scrollingHost\?\.removeEventListener\('scroll',onScroll\)/)
})
test('Browser-native animation bypasses conflicting stylesheet animation rules',()=>{
  const motion=get('ScrollTextAtmosphere.jsx')
  const css=get('scroll-text-atmosphere.css')
  assert.match(motion,/typeof Element\.prototype\.animate==='function'/)
  assert.match(motion,/root\.classList\.add\('pt-site--waapi-reveal'\)/)
  assert.match(motion,/target\.animate\(frames,\{[\s\S]*duration:options\.independentTiming\?options\.duration:ms\(options\.duration\)/)
  assert.match(motion,/delay:options\.independentTiming\?\(options\.delay\|\|0\):ms\(options\.delay\|\|0\)/)
  assert.match(motion,/animation\.onfinish=\(\)=>\{animation\.cancel\(\)\}/)
  assert.match(motion,/function animatePart\(node,state\)/)
  assert.match(motion,/if\(state==='visible'\|\|wasSeen\)animatePart\(node,state\)/)
  assert.match(css,/\.pt-site--waapi-reveal > section/)
  assert.match(css,/animation:none!important/)
  assert.match(css,/\[data-pt-reveal-state\^="hidden"\]\{\s*opacity:0/)
  assert.match(css,/\[data-pt-reveal-state="visible"\]\{\s*opacity:1/)
})
test('Title letters pop independently and each real or empty photo tile is revealed',()=>{
  const motion=get('ScrollTextAtmosphere.jsx')
  assert.match(motion,/node\.querySelectorAll\('\.pt-burst-letter'\)/)
  assert.match(motion,/letter\.index|letters\.forEach\(\(letter,index\)=>/)
  assert.match(motion,/delay:Math\.min\(240,index\*11\)/)
  assert.match(motion,/rotateX\(-28deg\)/)
  assert.match(motion,/pt-ribbon__tile--empty/)
  assert.match(motion,/pt-site__media-tile\.is-empty/)
  assert.match(motion,/pt-artboard__layer\.is-image/)
  assert.match(motion,/node\.querySelector\('\.pt-photo-motion'\)/)
  const css=get('scroll-text-atmosphere.css')
  assert.match(css,/pt-site--motion-paused/)
  assert.match(css,/prefers-reduced-motion:reduce/)
  assert.match(motion,/if\(motion\?\.matches&&!forceMotion\)return undefined/)
})
test('There is a user-triggered replay without changing portfolio save data',()=>{
  const editor=get('PortfolioInstanceEditor.jsx')
  const site=get('PortfolioTemplateSite.jsx')
  assert.match(editor,/↻ Xem hiệu ứng/)
  assert.match(editor,/Phát lại hiệu ứng chữ và ảnh ngay tại vị trí đang xem/)
  assert.match(editor,/setRevealReplayKey\(value=>value\+1\)/)
  assert.match(editor,/revealReplayKey=\{revealReplayKey\}/)
  assert.match(site,/revealReplayKey=0/)
  assert.match(site,/\+'\|replay:'\+revealReplayKey/)
})
